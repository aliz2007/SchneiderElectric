// Generates src/app/(shell)/analysis/world-geo.ts — static SVG paths for the zone map.
// One-off tool: run from a folder with `npm i topojson-client d3-geo world-atlas`,
// then `node generate-world-map.mjs` and copy world-geo.ts into place.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoNaturalEarth1, geoPath } from "d3-geo";

const require = createRequire(import.meta.url);
const world = require("world-atlas/countries-110m.json");

const MEA = new Set([
  // Africa
  "Algeria","Angola","Benin","Botswana","Burkina Faso","Burundi","Cameroon",
  "Central African Rep.","Chad","Congo","Dem. Rep. Congo","Djibouti","Egypt",
  "Eq. Guinea","Eritrea","Ethiopia","Gabon","Gambia","Ghana","Guinea",
  "Guinea-Bissau","Côte d'Ivoire","Kenya","Lesotho","Liberia","Libya",
  "Madagascar","Malawi","Mali","Mauritania","Morocco","Mozambique","Namibia",
  "Niger","Nigeria","Rwanda","Senegal","Sierra Leone","Somalia","Somaliland",
  "South Africa","S. Sudan","Sudan","eSwatini","Swaziland","Tanzania","Togo",
  "Tunisia","Uganda","W. Sahara","Zambia","Zimbabwe",
  // Middle East
  "Saudi Arabia","United Arab Emirates","Qatar","Kuwait","Oman","Yemen",
  "Jordan","Lebanon","Syria","Iraq","Israel","Palestine",
]);
const SAM = new Set([
  "Brazil","Argentina","Chile","Peru","Colombia","Venezuela","Ecuador",
  "Bolivia","Paraguay","Uruguay","Guyana","Suriname",
]);
const INDIA = new Set(["India","Sri Lanka","Bangladesh","Nepal","Bhutan"]);
const PACIFIC = new Set([
  "China","Taiwan","Japan","South Korea","Vietnam","Laos","Cambodia",
  "Thailand","Myanmar","Malaysia","Indonesia","Philippines","Brunei",
  "Papua New Guinea","Australia","New Zealand","Fiji","Solomon Is.",
  "Vanuatu","New Caledonia","Timor-Leste",
]);

const zoneOf = (name) =>
  MEA.has(name) ? "MEA" : SAM.has(name) ? "SAM" : INDIA.has(name) ? "India" : PACIFIC.has(name) ? "Pacific" : null;

const countries = feature(world, world.objects.countries).features.filter(
  (f) => f.properties.name !== "Antarctica"
);

const projection = geoNaturalEarth1().fitSize([980, 480], {
  type: "FeatureCollection",
  features: countries,
});
const path = geoPath(projection);

const round = (d) => d.replace(/(\d+\.\d+)/g, (m) => Number(m).toFixed(1));

const out = [];
const matched = { MEA: [], SAM: [], India: [], Pacific: [] };
for (const f of countries) {
  const d = path(f);
  if (!d) continue;
  const zone = zoneOf(f.properties.name);
  if (zone) matched[zone].push(f.properties.name);
  out.push({ name: f.properties.name, zone, d: round(d) });
}

// label anchor points (lon/lat → svg coords)
const labels = {
  MEA: projection([17, 6]),
  SAM: projection([-61, -11]),
  India: projection([78, 22]),
  Pacific: projection([134, -24]),
};

const ts = `// AUTO-GENERATED by scripts — world map paths (Natural Earth 110m, NaturalEarth1
// projection, 980×480 viewBox, Antarctica removed). Countries carry the APEX zone
// they belong to (null = not part of any zone). Regenerate rather than hand-edit.

export type MapZone = "MEA" | "SAM" | "India" | "Pacific";

export const ZONE_LABEL_XY: Record<MapZone, [number, number]> = {
  MEA: [${labels.MEA.map((n) => n.toFixed(1)).join(", ")}],
  SAM: [${labels.SAM.map((n) => n.toFixed(1)).join(", ")}],
  India: [${labels.India.map((n) => n.toFixed(1)).join(", ")}],
  Pacific: [${labels.Pacific.map((n) => n.toFixed(1)).join(", ")}],
};

export const WORLD_COUNTRIES: { name: string; zone: MapZone | null; d: string }[] = [
${out.map((c) => `  { name: ${JSON.stringify(c.name)}, zone: ${c.zone ? JSON.stringify(c.zone) : "null"}, d: ${JSON.stringify(c.d)} },`).join("\n")}
];
`;

writeFileSync("world-geo.ts", ts);
console.log("countries:", out.length, "| bytes:", ts.length);
for (const [z, names] of Object.entries(matched)) console.log(z, "→", names.length, "countries");
console.log("labels:", JSON.stringify(labels));
